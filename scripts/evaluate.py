"""Evaluate the assistant on every test clip and write docs/evaluation.md.

    python scripts/evaluate.py

We have no hand-labelled ground truth for these clips, so we measure what can be measured
honestly:
- speed (processing FPS),
- alert behavior, including clips where the assistant SHOULD stay silent (false alarms),
- distance consistency: depth-based distance vs. an independent estimate from a person's
  height in the image (pinhole camera: distance = focal_length * real_height / pixel_height).
"""

import time
from pathlib import Path

import cv2
import numpy as np
import torch

from blindnav.announcer import URGENT, Announcer, message, rank_alerts
from blindnav.depth import DepthEstimator, object_distance
from blindnav.detector import HAZARD_CLASS_CONF, Detector
from blindnav.risk import MotionTracker
from blindnav.spatial import SpatialAnalyzer, focal_length

PERSON_HEIGHT = 1.7  # m, average adult (men and women): a prior, not a measurement
DEPTH_SIZE, DEPTH_EVERY = 392, 2  # same defaults as run_video.py

# What a good assistant should do on each clip (our manual "ground truth").
EXPECTED = {
    "empty_street_1": "silent (nothing in the path)",
    "empty_street_2": "silent (nothing in the path)",
    "paris_crosswalk": "silent (pedestrians far away)",
    "person_approaching": "silent until the person is close (< 4 m)",
    "paris_alley_bw": "at most a warning about the person ahead",
    "paris_street_bollards": "few alerts; bollards are a known blind spot",
    "france_crosswalk_bollards": "warn about the crossing cyclist and the pole",
    "busy_street_night": "a few alerts about close vehicles/people, not a flood",
    "stairs_down": "warn about the stairs",
    "stairs_up": "warn about the stairs",
}


def evaluate_clip(path: Path, models) -> dict:
    detector, hazards, depth_estimator = models
    spatial, motion, announcer = SpatialAnalyzer(), MotionTracker(), Announcer()
    cap = cv2.VideoCapture(str(path))
    fps_video = cap.get(cv2.CAP_PROP_FPS) or 30
    alerts, ratios, blocked, n, depth = [], [], 0, 0, None
    start = time.perf_counter()
    while True:
        ok, frame = cap.read()
        if not ok:
            break
        h, w = frame.shape[:2]
        if w > 1280:
            frame = cv2.resize(frame, (1280, int(h * 1280 / w)))
        H, W = frame.shape[:2]
        t = n / fps_video

        detections = detector.detect(frame) + (hazards.detect(frame) if hazards else [])
        if depth is None or n % DEPTH_EVERY == 0:
            depth = depth_estimator.estimate(frame)
        for det in detections:
            det.distance = object_distance(depth, det.box)
        path_status = spatial.analyze(depth, detections)
        motion.update(t, detections, path_status, H)
        alert = announcer.decide(t, rank_alerts(detections, path_status))
        if alert:
            alerts.append((t, alert.level, message(alert)))
        blocked += path_status.blocked

        # Distance consistency check on fully visible people.
        f = focal_length(frame.shape)
        for det in detections:
            x1, y1, x2, y2 = det.box
            fully_visible = y1 > 2 and y2 < H - 2 and x1 > 2 and x2 < W - 2
            if det.class_name == "person" and fully_visible and y2 - y1 > 80 and det.distance:
                from_height = f * PERSON_HEIGHT / (y2 - y1)
                if from_height < 15:  # far away = tiny boxes = unreliable heights
                    ratios.append(det.distance / from_height)
        n += 1

    torch.cuda.synchronize()
    elapsed = time.perf_counter() - start
    minutes = n / fps_video / 60
    return {
        "clip": path.stem, "seconds": n / fps_video, "fps": n / elapsed,
        "alerts": alerts, "per_min": len(alerts) / minutes if minutes else 0,
        "urgent": sum(level == URGENT for _, level, _ in alerts),
        "blocked_pct": 100 * blocked / max(n, 1), "ratios": ratios,
    }


def main():
    models = (
        Detector("models/yolo11s.pt"),
        Detector("models/hazards.pt", all_classes=True, class_conf=HAZARD_CLASS_CONF,
                 id_offset=100_000) if Path("models/hazards.pt").exists() else None,
        DepthEstimator(input_size=DEPTH_SIZE),
    )
    results = []
    for name in EXPECTED:
        r = evaluate_clip(Path(f"data/videos/{name}.mp4"), models)
        results.append(r)
        print(f"{name:28s} {r['fps']:5.1f} FPS  {len(r['alerts'])} alerts", flush=True)

    all_ratios = np.concatenate([r["ratios"] for r in results if r["ratios"]])
    silent = [r for r in results if EXPECTED[r["clip"]].startswith("silent")]
    silent_minutes = sum(r["seconds"] for r in silent) / 60
    false_alarms = sum(len(r["alerts"]) for r in silent if r["clip"] != "person_approaching")

    lines = [
        "# Evaluation",
        "",
        f"Generated by `scripts/evaluate.py` on {torch.cuda.get_device_name(0)} "
        f"(depth {DEPTH_SIZE} px every {DEPTH_EVERY} frames, YOLO11s + hazard model, FP16). "
        "Processing speed includes all models but not video encoding.",
        "",
        "## Per clip",
        "",
        "| Clip | Length | Speed | Alerts | Urgent | Path blocked | Expected behavior | Spoken messages |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        spoken = "<br>".join(f"{t:.1f}s: {text}" for t, _, text in r["alerts"]) or "*(silence)*"
        lines.append(f"| {r['clip']} | {r['seconds']:.0f} s | {r['fps']:.1f} FPS | {len(r['alerts'])} "
                     f"| {r['urgent']} | {r['blocked_pct']:.0f}% | {EXPECTED[r['clip']]} | {spoken} |")
    lines += [
        "",
        "## Summary",
        "",
        f"- **Average speed:** {np.mean([r['fps'] for r in results]):.1f} FPS "
        f"(min {min(r['fps'] for r in results):.1f}, max {max(r['fps'] for r in results):.1f}).",
        f"- **False alarms on clips that should stay silent:** {false_alarms} "
        f"in {silent_minutes:.1f} minutes of video.",
        f"- **Overall alert rate:** {sum(len(r['alerts']) for r in results) / (sum(r['seconds'] for r in results) / 60):.1f} "
        "messages per minute.",
        f"- **Distance consistency (people):** depth-based distance / height-based distance = "
        f"median **{np.median(all_ratios):.2f}** (middle 50%: {np.percentile(all_ratios, 25):.2f}"
        f"-{np.percentile(all_ratios, 75):.2f}) over {len(all_ratios)} measurements. "
        "1.00 = both methods agree. Both depend on assumptions (1.7 m person, 70 deg field of "
        "view, 1.4 m camera height), so this checks consistency, not absolute accuracy.",
    ]
    Path("docs").mkdir(exist_ok=True)
    Path("docs/evaluation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[-6:]))
    print("\nWritten docs/evaluation.md")


if __name__ == "__main__":
    main()
